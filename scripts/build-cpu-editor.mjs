import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const modules=new Map(),chunks=[];
// The editor uses named imports and named declarations only. Fail on new syntax.
function bundle(file){
 file=path.resolve(file);if(modules.has(file))return modules.get(file);
 const id=`module${modules.size}`;modules.set(file,id);
 let source=fs.readFileSync(file,'utf8');
 source=source.replace(/import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?/g,(_,names,ref)=>{
  const dependency=bundle(path.resolve(path.dirname(file),ref.split('?')[0]));
  return `const {${names.replace(/\bas\b/g,':')}}=${dependency};`;
 });
 const exports=[];
 source=source.replace(/export\s+(const|let|function)\s+(\w+)/g,(_,kind,name)=>{exports.push(name);return `${kind} ${name}`;});
 if(/^\s*(import|export)\s/m.test(source))throw new Error(`Unsupported module syntax: ${file}`);
 chunks.push(`const ${id}=(()=>{\n${source}\nreturn {${exports.join(',')}};\n})();`);return id;
}
bundle(path.join(root,'js/cpu-editor.js'));
fs.writeFileSync(path.join(root,'js/cpu-editor.bundle.js'),'// Generated by node scripts/build-cpu-editor.mjs. Do not edit.\n(()=>{\n"use strict";\n'+chunks.join('\n')+'\n})();\n');
console.log(`Built standalone CPU editor (${modules.size} modules).`);
