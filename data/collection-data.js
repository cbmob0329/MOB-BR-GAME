function replacementMemberForCard(
  entry,
  replacementTeam,
) {
  return (
    replacementTeam.members.find(
      (member) =>
        member.role ===
        entry.role,
    ) ??
    replacementTeam.members.find(
      (member) =>
        member.id.endsWith(
          entry.slot,
        ),
    ) ??
    null
  );
}

export const CARD_COLLECTION =
  deepFreeze(
    LEGACY_CARD_COLLECTION.map(
      (entry) => {
        const replacement =
          getProReplacementTeamByLegacyId(
            entry.teamId,
          );
        if (!replacement) {
          return entry;
        }
        const member =
          replacementMemberForCard(
            entry,
            replacement,
          );
        if (!member) {
          throw new Error(
            `Replacement card member not found: ${entry.teamId}/${entry.role}`,
          );
        }
        return {
          ...entry,
          collectionId:
            `card:${member.id}`,
          tier:
            replacement.league,
          teamId:
            replacement.teamId,
          teamName:
            replacement.name,
          slot:
            member.id.at(-1),
          role:
            member.role,
          name:
            member.name,
          image:
            member.image,
        };
      },
    ),
  );

