export function calculateCollectionBonusRate(ownedRecord) {
  if (!ownedRecord || typeof ownedRecord !== "object") {
    return 0;
  }

  return Object.values(ownedRecord).reduce((total, owned) => {
    if (!owned || typeof owned !== "object" || owned.owned !== true) {
      return total;
    }
    const level = Number.isInteger(owned.level) ? owned.level : 0;
    return (
      total +
      COLLECTION_DUPLICATE_RULES.newTypeBonusRate +
      Math.min(
        COLLECTION_DUPLICATE_RULES.maximumLevel,
        Math.max(0, level),
      ) * COLLECTION_DUPLICATE_RULES.duplicateLevelBonusRate
    );
  }, 0);
}

export function getCollectionCompletion(ownedRecord, category) {
  const master =
    category === "card"
      ? CARD_COLLECTION
      : category === "badge"
        ? BADGE_COLLECTION
        : null;
  if (!master) {
    throw new RangeError(`Unknown collection category: ${category}`);
  }
  const ownedCount = master.filter(
    (entry) => ownedRecord?.[entry.collectionId]?.owned === true,
  ).length;
  return deepFreeze({
    ownedCount,
    totalCount: master.length,
    rate: master.length === 0 ? 0 : ownedCount / master.length,
  });
}

export function validateCollectionMaster() {
  if (CARD_COLLECTION.length !== 312) {
    throw new Error("Card collection must contain 312 entries.");
  }
  if (BADGE_COLLECTION.length !== 104) {
    throw new Error("Badge collection must contain 104 entries.");
  }
  if (ROOM_MASTER.length !== 16) {
    throw new Error("ROOM master must contain 16 rooms.");
  }

  const ids = [
    ...CARD_COLLECTION.map((entry) => entry.collectionId),
    ...BADGE_COLLECTION.map((entry) => entry.collectionId),
    ...ROOM_MASTER.map((entry) => entry.roomId),
  ];
  if (new Set(ids).size !== ids.length) {
    throw new Error("Duplicate collection or room ID detected.");
  }

  const tierCounts = Object.fromEntries(
    COLLECTION_TIER_DEFINITIONS.map((tier) => [
      tier.tier,
      {
        cards: CARD_COLLECTION.filter(
          (entry) => entry.tier === tier.tier,
        ).length,
        badges: BADGE_COLLECTION.filter(
          (entry) => entry.tier === tier.tier,
        ).length,
      },
    ]),
  );

  const expected = {
    local: { cards: 69, badges: 23 },
    national: { cards: 120, badges: 40 },
    world: { cards: 123, badges: 41 },
  };
  for (const [tier, counts] of Object.entries(expected)) {
    if (
      tierCounts[tier].cards !== counts.cards ||
      tierCounts[tier].badges !== counts.badges
    ) {
      throw new Error(`Invalid collection count for ${tier}.`);
    }
  }

  return deepFreeze({
    cardCount: CARD_COLLECTION.length,
    badgeCount: BADGE_COLLECTION.length,
    roomCount: ROOM_MASTER.length,
    tierCounts,
    valid: true,
  });
}
